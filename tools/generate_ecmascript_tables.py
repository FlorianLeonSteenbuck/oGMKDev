"""Generate ogmkdev/parsers/ecmascript_tables.py from KDevelop's QLALR-generated parser.

Reads the generated tables of the QML/JavaScript parser in the imported KDevelop source
(kdevelop/plugins/qmljs/3rdparty/qtcreator-libs/qmljs/parser/) and writes them as plain Python
data. The tables are not edited by hand. Run from the repository root:

    /usr/bin/python3.12 tools/generate_ecmascript_tables.py

The source is GPL-2.0-or-later (KDevelop); the generated data is a derivative of it.
"""

from __future__ import annotations

import os
import re
import sys
import textwrap

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SOURCE = os.path.join(ROOT, "kdevelop", "plugins", "qmljs", "3rdparty", "qtcreator-libs",
                      "qmljs", "parser")
OUTPUT = os.path.join(ROOT, "ogmkdev", "parsers", "ecmascript_tables.py")
ARRAYS = ("lhs", "rhs", "action_default", "goto_default", "action_index", "action_info", "action_check")


def read(name: str) -> str:
    with open(os.path.join(SOURCE, name), encoding="utf-8") as handle:
        return handle.read()


def enum_constants(header: str) -> dict:
    start = header.index("enum VariousConstants {")
    block = header[start:header.index("};", start)]
    return {name: int(value) for name, value in re.findall(r"(\w+)\s*=\s*(-?\d+)", block)}


def array_values(source: str, name: str) -> list:
    match = re.search(r"QmlJSGrammar::" + name + r"\s*\[\]\s*=\s*\{(.*?)\};", source, re.S)
    if not match:
        raise SystemExit(f"table {name} not found")
    body = re.sub(r"/\*.*?\*/", "", match.group(1), flags=re.S)
    return [int(value) for value in re.findall(r"-?\d+", body)]


def spell_values(source: str) -> list:
    match = re.search(r"QmlJSGrammar::spell\s*\[\]\s*=\s*\{(.*?)\};", source, re.S)
    values = []
    for quoted, _number in re.findall(r'"((?:[^"\\]|\\.)*)"|(-?\d+)', match.group(1)):
        values.append(quoted if quoted else None)  # 0 entries are unnamed terminals
    return values


def regexp_rules(parser_source: str) -> dict:
    rules = {}
    for number, prefix in re.findall(
            r"case (\d+): \{\s*bool rx = lexer->scanRegExp\(Lexer::(\w+)\)", parser_source):
        rules[int(number)] = prefix
    return rules


def format_list(name: str, values: list) -> str:
    body = ", ".join(repr(v) if isinstance(v, str) else str(v) for v in values)
    wrapped = textwrap.fill(body, width=96, initial_indent="    ", subsequent_indent="    ")
    return f"{name} = (\n{wrapped},\n)\n"


def main() -> int:
    header = read("qmljsgrammar_p.h")
    grammar = read("qmljsgrammar.cpp")
    parser = read("qmljsparser.cpp")
    constants = enum_constants(header)
    tables = {name: array_values(grammar, name) for name in ARRAYS}
    spell = spell_values(grammar)
    checks = {
        "lhs": len(tables["lhs"]) == constants["RULE_COUNT"],
        "rhs": len(tables["rhs"]) == constants["RULE_COUNT"],
        "action_default": len(tables["action_default"]) == constants["STATE_COUNT"],
        "goto_default": len(tables["goto_default"]) == constants["NON_TERMINAL_COUNT"],
        "action_index": len(tables["action_index"]) == 2 * constants["STATE_COUNT"],
        "spell": len(spell) == constants["TERMINAL_COUNT"],
    }
    failed = [name for name, ok in checks.items() if not ok]
    if failed:
        print("table sizes do not match the constants:", failed, file=sys.stderr)
        return 1
    regex_rules = regexp_rules(parser)
    if regex_rules.get(96) != "NoPrefix" or regex_rules.get(97) != "EqualPrefix":
        print("regular expression rules changed:", regex_rules, file=sys.stderr)
        return 1

    lines = [
        '"""ECMAScript parser tables generated from KDevelop\'s QLALR output.',
        "",
        "Generated by tools/generate_ecmascript_tables.py from kdevelop/plugins/qmljs/3rdparty/",
        "qtcreator-libs/qmljs/parser/ (qmljsgrammar.cpp, qmljsgrammar_p.h, qmljsparser.cpp).",
        "Do not edit by hand. The data is derived from KDevelop (GPL-2.0-or-later).",
        '"""',
        "",
        f"CONSTANTS = {{",
    ]
    for name in sorted(constants):
        lines.append(f"    {name!r}: {constants[name]},")
    lines.append("}")
    lines.append("")
    lines.append(format_list("SPELL", spell))
    for name in ARRAYS:
        lines.append(format_list(name.upper(), tables[name]))
    lines.append(f"REGEXP_RULES = {regex_rules!r}")
    lines.append("")
    with open(OUTPUT, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {OUTPUT}: {len(spell)} terminals, {constants['RULE_COUNT']} rules, "
          f"{constants['STATE_COUNT']} states, {len(tables['action_info'])} action entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
